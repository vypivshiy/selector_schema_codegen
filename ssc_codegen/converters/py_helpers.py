def _module_has_rest(node: a.Node) -> bool:
    """True if the node's enclosing Module has any ``struct type=rest``."""
    module: a.Node | None = node
    while module is not None and not isinstance(module, a.Module):
        module = getattr(module, "parent", None)
    if module is None:
        return False
    return any(
        isinstance(n, a.Struct) and n.is_rest
        for n in getattr(module, "body", [])
    )


def module_is_rest_only(node: a.Node) -> bool:
    """True if the module has no HTML-parsing structs (all rest or empty)."""
    module: a.Node | None = node
    while module is not None and not isinstance(module, a.Module):
        module = getattr(module, "parent", None)
    if module is None:
        return False
    structs = [
        n for n in getattr(module, "body", []) if isinstance(n, a.Struct)
    ]
    return len(structs) == 0 or all(s.is_rest for s in structs)


def rest_imports(node: a.Node) -> list[str]:
    """Extra imports required when the module has any ``struct type=rest``."""
    if not _module_has_rest(node):
        return []
    return [
        "from dataclasses import dataclass, field",
        "from typing import Generic, Literal, Mapping, TypeVar",
    ]


def http_client_import(ctx: ConverterContext) -> list[str]:
    """Return the import line(s) for the chosen HTTP client, or ``[]``."""
    client = ctx.meta.get("http_client", "")
    if client == "requests":
        return ["import requests"]
    if client == "httpx":
        return ["import httpx"]
    return []


def rest_utilities(node: a.Node) -> list[str]:
    """Ok/Err/UnknownErr/TransportErr + _parse_response block; empty if no REST."""
    if not _module_has_rest(node):
        return []
    return [
        "_T = TypeVar('_T')",
        "_E = TypeVar('_E')",
        "\n",
        "@dataclass(frozen=True)",
        "class Ok(Generic[_T]):",
        "    status: int = 0",
        "    headers: Mapping[str, str] = field(default_factory=dict)",
        "    value: _T = None  # type: ignore[assignment]",
        "    is_ok: Literal[True] = True",
        "\n",
        "@dataclass(frozen=True)",
        "class Err(Generic[_E]):",
        "    status: int = 0",
        "    headers: Mapping[str, str] = field(default_factory=dict)",
        "    value: _E = None  # type: ignore[assignment]",
        "    is_ok: Literal[False] = False",
        "\n",
        "@dataclass(frozen=True)",
        "class UnknownErr(Err[Any]):",
        "    pass",
        "\n",
        "@dataclass(frozen=True)",
        "class TransportErr(Err[None]):",
        "    status: Literal[0] = 0",
        "    cause: str = ''",
        "    value: None = None",
        "    headers: Mapping[str, str] = field(default_factory=dict)",
        "\n\n",
        "def _parse_response(_resp):",
        "    _status = _resp.status_code",
        "    _headers = {k.lower(): v for k, v in _resp.headers.items()}",
        "    try:",
        "        _body = _resp.json()",
        "    except Exception:",
        "        _body = None",
        "    return _status, _headers, _body",
        "\n\n",
    ]


