def base_utility_lines(*, include_fallback_html: bool = False) -> list[str]:
    """Return the standard utility helper lines for generated code.

    Single source of truth replacing inline copies in py_bs4 / py_lxml.
    """
    lines: list[str] = []
    if include_fallback_html:
        lines.append('FALLBACK_HTML_STR = "<html><body></body></html>"')
        lines.append("")
    lines.extend(_BASE_UTILITY_LINES)
    lines.append("")
    return lines


def runtime_export_names(
    node: a.Node, include_fallback_html: bool = False
) -> list[str]:
    """Names the main module must import from the runtime module."""
    names = list(_BASE_EXPORT_NAMES)
    if include_fallback_html:
        names.append("FALLBACK_HTML_STR")
    if _module_has_rest(node):
        names.extend(
            ["Ok", "Err", "UnknownErr", "TransportErr", "_parse_response"]
        )
    return names


def runtime_module_content(
    node: a.Node, include_fallback_html: bool = False
) -> str:
    """Full content of the runtime module as a string."""
    lines: list[str] = [
        "# autogenerated runtime helpers — do not edit",
        "import re",
        "import sys",
        "from typing import Dict",
        "from html import unescape as _html_unescape",
    ]
    has_rest = _module_has_rest(node)
    if has_rest:
        lines.extend(
            [
                "from dataclasses import dataclass, field",
                "from typing import Any, Generic, Literal, Mapping, TypeVar",
            ]
        )
    lines.append("")
    lines.append("")
    if include_fallback_html:
        lines.append('FALLBACK_HTML_STR = "<html><body></body></html>"')
        lines.append("")
    lines.extend(_BASE_UTILITY_LINES)
    lines.append("")
    if has_rest:
        lines.extend(rest_utilities(node))
    return "\n".join(lines)


