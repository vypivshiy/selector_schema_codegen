def _emit_table_parse_body(
    node: a.StartParse, ctx: ConverterContext
) -> list[str]:
    parent = node.struct
    i2, i3, i4 = ctx.indent * 2, ctx.indent * 3, ctx.indent * 4
    name = to_pascal_case(parent.name)
    lines = [f"{i2}_result: {name}Type = {{}}"]
    lines.extend(
        [
            f"{i2}_table = self._table_config(self._doc)",
            f"{i2}for _row in self._parse_table_rows(_table):",
        ]
    )
    for f in node.fields:
        fname = to_snake_case(f.name)
        lines.append(f"{i3}_{fname} = self._parse_{fname}(_row)")
        lines.append(
            f"{i3}if _{fname} != UNMATCHED_TABLE_ROW and {fname!r} not in _result:"
        )
        lines.append(f"{i4}_result[{fname!r}] = _{fname}")
    lines.append(f"{i2}return _result")
    return lines


