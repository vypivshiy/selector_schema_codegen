PY_TYPES = {
    VT.STRING: "str",
    VT.BOOL: "bool",
    VT.INT: "int",
    VT.FLOAT: "float",
    VT.NULL: "None",
    VT.JSON: "Any",
    VT.NESTED: "Any",
    VT.DOCUMENT: "Union[Tag, BeautifulSoup]",
    VT.AUTO: "Any",
}


def _resolve_py_type(type_info: a.TypeInfo | None) -> str:
    """Render TypeInfo into a Python type annotation string."""
    if type_info is None:
        return "Any"
    if type_info.base == VT.NESTED and type_info.ref:
        type_ = f"{to_pascal_case(type_info.ref)}Type"
    elif type_info.base == VT.JSON and type_info.ref:
        type_ = f"{to_pascal_case(type_info.ref)}Json"
    else:
        type_ = PY_TYPES.get(type_info.base, "Any")
    if type_info.is_array:
        type_ = f"List[{type_}]"
    if type_info.is_optional:
        type_ = f"Optional[{type_}]"
    return type_


@PY_BASE_CONVERTER(a.Module)
def pre_module(node: a.Module, ctx: ConverterContext):
    lines = ["# autogenerated by ssc-gen. DO NOT EDIT"]
    if node.doc:
        lines.append(f'"""{node.doc}"""')

    runtime = ctx.meta.get("runtime_module")
    if runtime:
        base_imports = [
            "import json",
            "import re",
            "import sys",
            "from dataclasses import dataclass",
            "from typing import TypedDict, Optional, Any, List, Dict, Union, Literal, Mapping",
        ]
        base_imports.extend(NOT_REQUIRED_IMPORT)
    else:
        base_imports = [
            "import json",
            "import re",
            "import sys",
            "from dataclasses import dataclass",
            "from typing import TypedDict, Optional, Any, List, Dict, Union, Literal, Mapping",
        ]
        if not module_is_rest_only(node):
            base_imports.append(
                "from html import unescape as ssc_html_unescape"
            )
        base_imports.extend(NOT_REQUIRED_IMPORT)
        base_imports.extend(rest_imports(node))
    lines.extend(base_imports)

    if not module_is_rest_only(node):
        lines.extend(
            [
                "from bs4 import BeautifulSoup, ResultSet, Tag",
                "BS4_FEATURES = 'lxml'",
            ]
        )
    lines.extend(http_client_import(ctx))

    return lines


@PY_BASE_CONVERTER(a.Utilities)
def pre_utilities(node: a.Utilities, ctx: ConverterContext):
    module = node.parent
    assert isinstance(module, a.Module)
    runtime = ctx.meta.get("runtime_module")
    if runtime:
        names = runtime_export_names(module)
        return [f"from .{runtime} import " + ", ".join(names), ""]

    if module_is_rest_only(module):
        lines = []
        lines.extend(rest_utilities(module))
        return lines

    lines = base_utility_lines()
    lines.extend(rest_utilities(module))
    return lines


