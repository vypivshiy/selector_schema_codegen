@PY_BASE_CONVERTER(a.StructRest)
def pre_struct_rest(node: a.StructRest, ctx: ConverterContext):
    name = to_pascal_case(node.name)
    lines: list[str] = []
    # Error subclasses (module-level, before class body)
    seen: set[str] = set()
    for err in node.errors:
        cls_name = err_subclass_name(node.name, err)
        if cls_name in seen:
            continue
        seen.add(cls_name)
        value_type = err_value_type(err, node)
        lines.append("@dataclass(frozen=True)")
        lines.append(f"class {cls_name}(Err[{value_type}]):")
        lines.append(f"    status: Literal[{err.status}] = {err.status}")
        lines.append("")
    # Result type aliases (module-level, before class body)
    alias_lines = _emit_result_aliases(node)
    if alias_lines:
        lines.extend(alias_lines)
        lines.append("")
    # Class header
    lines.append(f"class {name}:")
    # ssc_dispatch_err staticmethod (first member of class body, needs class-level indent)
    lines.extend(_emit_dispatch_err(node, ctx.deeper()))
    return lines


