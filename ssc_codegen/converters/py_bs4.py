_PH_PRIM_ANNO: dict[str, str] = {
    "str": "str",
    "int": "int",
    "float": "float",
    "bool": "bool",
}


def _ph_to_py_annotation(ph: PlaceholderSpec) -> tuple[str, str]:
    anno = _PH_PRIM_ANNO[ph.type_name]
    if ph.is_array:
        anno = f"List[{anno}]"
    if ph.is_optional:
        return f"Optional[{anno}]", " = None"
    return anno, ""


def _render_signature_params(placeholders: list[PlaceholderSpec]) -> str:
    if not placeholders:
        return ""
    required = [p for p in placeholders if not p.is_optional]
    optional = [p for p in placeholders if p.is_optional]
    parts: list[str] = []
    for ph in required + optional:
        anno, default = _ph_to_py_annotation(ph)
        parts.append(f"{ph.name}: {anno}{default}")
    return ", *, " + ", ".join(parts)


def _build_request_parts(node: a.RequestConfig, ctx: ConverterContext):
    """Parse raw HTTP payload and build all request components."""
    spec = normalize_placeholder_names(
        parse_to_spec(node.raw_payload), to_snake_case
    )
    ind = ctx.indent_char
    i1 = ctx.indent
    i2 = i1 + ind
    i3 = i2 + ind
    i4 = i3 + ind

    ph_params = _render_signature_params(spec.placeholders)
    pre_lines: list[str] = []
    call_args: list[str] = [f"{spec.method!r},", f"{render_value(spec.url)},"]

    def _dict_arg(kwarg: str, d: dict[str, str], varname: str) -> None:
        if not d:
            return
        if dict_needs_builder(d):
            pre_lines.extend(emit_dict_builder(varname, d, i2))
            call_args.append(f"{kwarg}={varname},")
        else:
            call_args.append(f"{kwarg}={render_dict(d)},")

    _dict_arg("headers", spec.headers, "_headers")
    _dict_arg("cookies", spec.cookies, "_cookies")
    _dict_arg("params", spec.params, "_params")
    body_result = render_body(spec)
    if body_result:
        kwarg_name, body_expr = body_result
        call_args.append(f"{kwarg_name}={body_expr},")

    return spec, call_args, pre_lines, ph_params, i1, i2, i3, i4


def _emit_rest_methods(
    node: a.RequestConfig,
    call_args: list[str],
    pre_lines: list[str],
    ph_params: str,
    i1: str,
    i2: str,
    i3: str,
    i4: str,
) -> list[str]:
    method_name = to_snake_case(node.name) if node.name else "fetch"
    ret_type = _result_alias_name(node.name)
    ok_value = "_body" if node.response_schema else "None"
    lines: list[str] = []
    for is_async, mname, ctype in [
        (False, method_name, "httpx.Client"),
        (True, f"async_{method_name}", "httpx.AsyncClient"),
    ]:
        akw = "async " if is_async else ""
        awk = "await " if is_async else ""
        lines.append(f"{i1}@classmethod")
        lines.append(
            f"{i1}{akw}def {mname}(cls, client: {ctype}{ph_params}) -> {ret_type}:"
        )
        if node.doc:
            lines.append(f'{i2}"""{node.doc}"""')
        lines.extend(pre_lines)
        lines.append(f"{i2}try:")
        lines.append(f"{i3}_resp = {awk}client.request(")
        lines.extend(f"{i4}{a}" for a in call_args)
        lines.append(f"{i3})")
        lines.append(f"{i2}except httpx.HTTPError as _exc:")
        lines.append(f"{i3}return TransportErr(cause=repr(_exc))")
        lines.append(
            f"{i2}_status, _headers, _body = ssc_parse_response(_resp)"
        )
        lines.append(
            f"{i2}_err = cls.ssc_dispatch_err(_status, _headers, _body)"
        )
        lines.append(f"{i2}if _err is not None:")
        lines.append(f"{i3}return _err")
        lines.append(
            f"{i2}return Ok(status=_status, headers=_headers, value={ok_value})"
        )
        lines.append("")
    lines.pop()
    return lines


def _emit_fetch_methods(
    node: a.RequestConfig,
    call_args: list[str],
    pre_lines: list[str],
    ph_params: str,
    i1: str,
    i2: str,
    i3: str,
) -> list[str]:
    struct_name = to_pascal_case(node.parent.name)  # type: ignore[union-attr]
    suffix = ("_" + to_snake_case(node.name)) if node.name else ""
    response_path = node.response_path
    response_join = node.response_join
    lines: list[str] = []
    for is_async, mname, ctype in [
        (False, f"fetch{suffix}", "httpx.Client"),
        (True, f"async_fetch{suffix}", "httpx.AsyncClient"),
    ]:
        akw = "async " if is_async else ""
        awk = "await " if is_async else ""
        lines.append(f"{i1}@classmethod")
        lines.append(
            f'{i1}{akw}def {mname}(cls, client: {ctype}{ph_params}) -> "{struct_name}":'
        )
        lines.extend(pre_lines)
        lines.append(f"{i2}_resp = {awk}client.request(")
        lines.extend(f"{i3}{a}" for a in call_args)
        lines.append(f"{i2})")
        lines.append(f"{i2}_resp.raise_for_status()")
        if response_path:
            accessor = "".join(f"[{p!r}]" for p in response_path.split("."))
            lines.append(f"{i2}_data = _resp.json()")
            if response_join:
                lines.append(
                    f"{i2}_body = {response_join!r}.join(_data{accessor})"
                )
            else:
                lines.append(f"{i2}_body = _data{accessor}")
        else:
            lines.append(f"{i2}_body = _resp.text")
        lines.append(f"{i2}return cls(_body)")
        lines.append("")
    lines.pop()
    return lines


@PY_BASE_CONVERTER(a.RequestConfig)
def pre_request_config(node: a.RequestConfig, ctx: ConverterContext):
    _, call_args, pre_lines, ph_params, i1, i2, i3, i4 = _build_request_parts(
        node, ctx
    )
    if isinstance(node.parent, a.StructRest):
        return _emit_rest_methods(
            node, call_args, pre_lines, ph_params, i1, i2, i3, i4
        )
    return _emit_fetch_methods(
        node, call_args, pre_lines, ph_params, i1, i2, i3
    )


