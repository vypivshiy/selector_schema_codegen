@PY_BASE_CONVERTER(a.JsonDefField)
def pre_json_field(node: a.JsonDefField, ctx: ConverterContext):
    if node.skip:
        return None
    name = node.alias or node.name
    type_ = PY_TYPES.get(node.ret, "Any")
    if node.ret == VT.JSON and node.ref_name:
        type_name = to_pascal_case(node.ref_name)
        type_ = type_.format(type_name)
        if node.is_array:
            type_ = f"List[{type_}]"
    if node.is_optional:
        type_ = f"Optional[{type_}]"
    if node.may_miss:
        type_ = f"NotRequired[{type_}]"
    return [f"{name!r}: {type_}, "]


@PY_BASE_CONVERTER(a.TypeDef)
def pre_typedef(node: a.TypeDef, _: ConverterContext):
    name = to_pascal_case(node.name)
    if node.struct_type == a.StructType.REST:
        # REST structs are API clients, not data types — no type alias
        return None
    if node.struct_type == a.StructType.DICT:
        return None
    elif node.struct_type == a.StructType.FLAT:
        return f"{name}Type = List[str]"
    return f"class {name}Type(TypedDict):"


@PY_BASE_CONVERTER(a.TypeDefField)
def pre_typedef_field(node: a.TypeDefField, ctx: ConverterContext):
    # alreay created type, skip
    if node.typedef.struct_type == a.StructType.FLAT:
        return
    name = to_snake_case(node.name)
    type_ = PY_TYPES.get(node.ret, "Any")
    if node.ret == VT.JSON and node.json_ref:
        type_name = to_pascal_case(node.json_ref)
        type_ = type_.format(type_name)
        if node.is_array:
            type_ = f"List[{type_}]"
    elif node.ret == VT.NESTED and node.nested_ref:
        type_name = to_pascal_case(node.nested_ref)
        type_ = type_.format(type_name)
        if node.is_array:
            type_ = f"List[{type_}]"
    if node.typedef.struct_type == a.StructType.DICT:
        if to_snake_case(node.name) == "value":
            typedef_name = to_pascal_case(node.typedef.name)
            return f"{typedef_name}Type = Dict[str, {type_}]"
        return None
    return [f"{ctx.indent}{name}: {type_}"]


