def _emit_py_struct_doc(node: a.StructBase, ctx: ConverterContext) -> list[str]:
    """Emit a Python class docstring block (inside the class body).

    Returns an empty list when ``node.doc`` is empty.
    """
    if not node.doc:
        return []
    lines = [f'{ctx.indent}"""']
    lines.extend(f"{ctx.indent}{line}" for line in node.doc.splitlines())
    lines.append(f'{ctx.indent}"""')
    return lines


def _py_class_header(node: a.StructBase, ctx: ConverterContext) -> list[str]:
    """Emit ``class Name:`` followed by an optional docstring block."""
    lines = [f"class {to_pascal_case(node.name)}:"]
    lines.extend(_emit_py_struct_doc(node, ctx.deeper()))
    return lines


